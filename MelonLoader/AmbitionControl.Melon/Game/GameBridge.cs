using System;
using Il2Cpp;

namespace AmbitionControl.Game
{
    /// <summary>
    /// Immutable copy of the game values we display. Captured on the main thread in OnUpdate;
    /// the UI only reads this copy and never holds live Il2Cpp objects across frames.
    /// </summary>
    internal sealed class GameSnapshot
    {
        internal bool Loaded;
        internal string NotLoadedReason;
        internal IntPtr InstancePtr;
        internal string SaveName;
        internal string CharacterId;
        internal float Money;
        internal float NetWorth;
        internal float Energy;
        internal float Hunger;
        internal float Happiness;
        internal int Day;
        internal int Hour;
        internal float Minute;
        internal bool Saving;
        internal bool OptionsKnown;
        internal bool[] OptionDisabled = new bool[GameOptions.All.Length];

        internal bool SameSession(SaveIdentity id) =>
            Loaded && id != null && id.InstancePtr == InstancePtr &&
            string.Equals(id.SaveName, SaveName, StringComparison.Ordinal) &&
            string.Equals(id.CharacterId, CharacterId, StringComparison.Ordinal);

        internal SaveIdentity Identity() => new SaveIdentity(InstancePtr, SaveName, CharacterId);
    }

    internal sealed class SaveIdentity
    {
        internal readonly IntPtr InstancePtr;
        internal readonly string SaveName;
        internal readonly string CharacterId;

        internal SaveIdentity(IntPtr ptr, string saveName, string characterId)
        {
            InstancePtr = ptr;
            SaveName = saveName;
            CharacterId = characterId;
        }
    }

    /// <summary>
    /// Typed adapter over the generated Il2Cpp interop for Big Ambitions build 3233.
    /// Every member used here was confirmed in MelonLoader\Il2CppAssemblies\Il2CppBigAmbitions.dll
    /// (generated by MelonLoader 0.7.3) and is bound at compile time, so a signature change in a
    /// different game build surfaces as a MissingMethodException that we catch and report.
    ///   SaveGameManager.Current : GameInstance (static)
    ///   SaveGameManager.SavingGameInProgress : bool (static)
    ///   GameInstance.Money/NetWorth/Energy/Hunger/Happiness/Minute : float, Day/Hour : int,
    ///   GameInstance.SaveGameName/characterId : string, CityInitialized : bool
    ///   GameManager.ChangeMoneySafe(float, Transaction.TransactionType, Transaction.DataHolder,
    ///       Nullable&lt;int&gt;, Address, bool force, bool showNotification) : bool (static)
    ///   GameVersion.GetCurrent().buildNumber : int
    /// </summary>
    internal static class GameBridge
    {
        internal const int TargetBuild = 3233;

        private static int? buildNumber;
        private static string buildError;

        internal static int? BuildNumber => buildNumber;
        internal static string BuildError => buildError;

        /// <summary>Resolve the running game's build number once it is available.</summary>
        internal static void TryResolveBuild()
        {
            if (buildNumber.HasValue) return;
            try
            {
                GameVersion version = GameVersion.GetCurrent();
                if (version != null)
                {
                    buildNumber = version.buildNumber;
                    buildError = null;
                }
            }
            catch (Exception ex)
            {
                buildError = ex.GetType().Name + ": " + ex.Message;
            }
        }

        internal static GameSnapshot Capture()
        {
            var snap = new GameSnapshot();
            GameInstance gi;
            try
            {
                gi = SaveGameManager.Current;
            }
            catch (Exception ex)
            {
                snap.NotLoadedReason = "Save manager unavailable: " + ex.GetBaseException().Message;
                return snap;
            }

            if (gi == null || gi.Pointer == IntPtr.Zero)
            {
                snap.NotLoadedReason = "No save loaded (main menu).";
                return snap;
            }

            try
            {
                if (!gi.CityInitialized)
                {
                    snap.NotLoadedReason = "Save is loading...";
                    return snap;
                }
                snap.InstancePtr = gi.Pointer;
                snap.SaveName = gi.SaveGameName;
                snap.CharacterId = gi.characterId;
                snap.Money = gi.Money;
                snap.NetWorth = gi.NetWorth;
                snap.Energy = gi.Energy;
                snap.Hunger = gi.Hunger;
                snap.Happiness = gi.Happiness;
                snap.Day = gi.Day;
                snap.Hour = gi.Hour;
                snap.Minute = gi.Minute;
                snap.Saving = SaveGameManager.SavingGameInProgress;
                GameVariables gv = gi.gameVariables;
                if (gv != null)
                {
                    snap.OptionsKnown = true;
                    foreach (GameOption o in GameOptions.All)
                        snap.OptionDisabled[(int)o] = GameOptions.ReadDisabled(gv, o);
                }
                snap.Loaded = true;
            }
            catch (Exception ex)
            {
                snap = new GameSnapshot { NotLoadedReason = "Read failed: " + ex.GetBaseException().Message };
            }
            return snap;
        }

        /// <summary>Read only the live balance (used for post-write verification).</summary>
        internal static bool TryReadMoney(SaveIdentity expected, out float money)
        {
            money = 0f;
            GameInstance gi = SaveGameManager.Current;
            if (gi == null || gi.Pointer != expected.InstancePtr) return false;
            money = gi.Money;
            return true;
        }

        /// <summary>
        /// Calls the game's own money transaction path using its built-in "Cheat" transaction type,
        /// so the change is recorded and displayed like any other transaction. force=false lets the
        /// game refuse invalid changes. Must be called on the main thread.
        /// </summary>
        internal static bool ChangeMoney(float delta)
        {
            var data = new Transaction.DataHolder();
            var noDay = new Il2CppSystem.Nullable<int>();
            return GameManager.ChangeMoneySafe(delta, Transaction.TransactionType.Cheat, data, noDay,
                null, false, true);
        }
    }
}
